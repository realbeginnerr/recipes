export function translateUi(text: string, language: Language): string {
  if (language === 'ko') return text
  if (!/[가-힣]/.test(text)) return text
  const exact = englishUiCopy[text.trim()] ?? englishUiErrors[text.trim()]
  if (exact !== undefined) return exact
  for (const [pattern, replacement] of Object.entries(englishUiPatterns)) {
    const escaped = pattern.split(/\{\d+\}/).map(part => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('(.+?)')
    const match = new RegExp(`^${escaped}$`).exec(text)
    if (match) return replacement.replace(/\{(\d+)\}/g, (_, index: string) => match[Number(index) + 1])
  }
  return text
}
